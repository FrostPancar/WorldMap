// ---------------------------------------------------------------------------
// Pixel glyph registry. Every tile decoration, structure and creature is a
// small bitmap written as text: '.' = transparent, digits = palette slot.
// Glyphs are rasterised lazily into cached canvases (with optional h-flip and
// "emissive only" variants used by the glow layer).
// ---------------------------------------------------------------------------

const TS = 8; // tile size in pixels

const GLYPHS = [null];
const G = Object.create(null);

function defGlyph(name, frames, colors, opts) {
  opts = opts || {};
  if (typeof frames[0] === 'string') frames = [frames];
  const h = frames[0].length, w = frames[0][0].length;
  const def = {
    id: GLYPHS.length, name, frames, colors, w, h,
    anim: opts.anim || 0,            // frames per second (0 = static)
    emit: opts.emit || null,         // true or list of palette slots that glow
    light: opts.light || null,       // {c, r, i, f, ox, oy}
    mapColor: opts.mapColor || colors[0],
    tags: opts.tags || '',
  };
  if (def.light) def.light.rgb = hexToRgb(def.light.c);
  def.mini = makeMini(frames[0]);
  GLYPHS.push(def);
  G[name] = def.id;
  return def.id;
}

function variant(name, base, colors, opts) {
  const b = GLYPHS[G[base]];
  opts = Object.assign({ anim: b.anim, emit: b.emit, light: b.light && Object.assign({}, b.light), tags: b.tags }, opts || {});
  if (opts.light === false) opts.light = null;
  return defGlyph(name, b.frames, colors, opts);
}

// Half-resolution version of a bitmap for the world map.
function makeMini(rows) {
  const w = rows[0].length >> 1, h = rows.length >> 1;
  const data = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const cnt = {};
    let best = 0, bc = 0, n = 0;
    for (let j = 0; j < 2; j++) for (let i = 0; i < 2; i++) {
      const ch = rows[y * 2 + j][x * 2 + i];
      if (ch !== '.') {
        n++;
        cnt[ch] = (cnt[ch] || 0) + 1;
        if (cnt[ch] > bc) { bc = cnt[ch]; best = +ch; }
      }
    }
    data[y * w + x] = n >= 1 ? best : 0;
  }
  return { w, h, data };
}

const _sprCache = new Map();
function spr(id, frame, flip, emitOnly) {
  const key = id * 64 + (frame || 0) * 4 + (flip ? 2 : 0) + (emitOnly ? 1 : 0);
  let c = _sprCache.get(key);
  if (c) return c;
  const d = GLYPHS[id];
  const rows = d.frames[(frame || 0) % d.frames.length];
  c = document.createElement('canvas');
  c.width = d.w; c.height = d.h;
  const x = c.getContext('2d');
  const img = x.createImageData(d.w, d.h);
  const rgb = d.colors.map(hexToRgb);
  const emitSet = d.emit === true ? null : d.emit;
  for (let y = 0; y < d.h; y++) for (let i = 0; i < d.w; i++) {
    const ch = rows[y][i];
    if (ch === '.') continue;
    const ci = +ch;
    if (emitOnly && emitSet && emitSet.indexOf(ci) < 0) continue;
    const col = rgb[ci - 1] || [255, 0, 255];
    const px = flip ? d.w - 1 - i : i;
    const o = (y * d.w + px) * 4;
    img.data[o] = col[0]; img.data[o + 1] = col[1]; img.data[o + 2] = col[2]; img.data[o + 3] = 255;
  }
  x.putImageData(img, 0, 0);
  _sprCache.set(key, c);
  return c;
}

